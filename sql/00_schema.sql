CREATE TABLE departments (
    department_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_name VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE employees (
    employee_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(150) NOT NULL,
    hire_date DATE NOT NULL,
    department_id INTEGER NOT NULL,
    CONSTRAINT fk_employees_department FOREIGN KEY (department_id) REFERENCES departments (department_id) ON DELETE RESTRICT
);

CREATE TABLE digital_tools (
    tool_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tool_name VARCHAR(100) NOT NULL UNIQUE,
    category VARCHAR(50) NOT NULL,
    launch_date DATE NOT NULL
);

CREATE TABLE tool_access (
    access_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id INTEGER NOT NULL,
    tool_id INTEGER NOT NULL,
    access_granted_date DATE NOT NULL,
    access_revoked_date DATE NULL,
    CONSTRAINT fk_access_employee FOREIGN KEY (employee_id) REFERENCES employees (employee_id) ON DELETE RESTRICT,
    CONSTRAINT fk_access_tool FOREIGN KEY (tool_id) REFERENCES digital_tools (tool_id) ON DELETE RESTRICT,
    CONSTRAINT uq_employee_tool_access UNIQUE (employee_id, tool_id),
    CONSTRAINT chk_access_dates CHECK (
        access_revoked_date IS NULL
        OR access_revoked_date >= access_granted_date
    )
);

CREATE TABLE usage_events (
    usage_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id INTEGER NOT NULL,
    tool_id INTEGER NOT NULL,
    usage_date DATE NOT NULL,
    session_count INTEGER NOT NULL,
    active_minutes INTEGER NOT NULL,
    CONSTRAINT fk_usage_employee FOREIGN KEY (employee_id) REFERENCES employees (employee_id) ON DELETE RESTRICT,
    CONSTRAINT fk_usage_tool FOREIGN KEY (tool_id) REFERENCES digital_tools (tool_id) ON DELETE RESTRICT,
    CONSTRAINT fk_usage_valid_access FOREIGN KEY (employee_id, tool_id) REFERENCES tool_access (employee_id, tool_id) ON DELETE RESTRICT,
    CONSTRAINT uq_usage_granularity UNIQUE (employee_id, tool_id, usage_date),
    CONSTRAINT chk_usage_positive_metrics CHECK (
        session_count > 0
        AND active_minutes > 0
    )
);

CREATE TABLE support_tickets (
    ticket_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id INTEGER NOT NULL,
    tool_id INTEGER NOT NULL,
    opened_at TIMESTAMP NOT NULL,
    resolved_at TIMESTAMP NULL,
    category VARCHAR(50) NOT NULL,
    priority VARCHAR(20) NOT NULL,
    CONSTRAINT fk_tickets_employee FOREIGN KEY (employee_id) REFERENCES employees (employee_id) ON DELETE RESTRICT,
    CONSTRAINT fk_tickets_tool FOREIGN KEY (tool_id) REFERENCES digital_tools (tool_id) ON DELETE RESTRICT,
    CONSTRAINT chk_ticket_dates CHECK (
        resolved_at IS NULL
        OR resolved_at >= opened_at
    ),
    CONSTRAINT chk_ticket_category CHECK (
        category IN (
            'Access/Permission',
            'Usage Question',
            'Error/Bug',
            'Integration'
        )
    ),
    CONSTRAINT chk_ticket_priority CHECK (
        priority IN ('Low', 'Medium', 'High', 'Critical')
    )
);

CREATE TABLE training_records (
    training_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id INTEGER NOT NULL,
    tool_id INTEGER NOT NULL,
    training_date DATE NOT NULL,
    completion_status VARCHAR(20) NOT NULL,
    CONSTRAINT fk_training_employee FOREIGN KEY (employee_id) REFERENCES employees (employee_id) ON DELETE RESTRICT,
    CONSTRAINT fk_training_tool FOREIGN KEY (tool_id) REFERENCES digital_tools (tool_id) ON DELETE RESTRICT,
    CONSTRAINT uq_training_session UNIQUE (employee_id, tool_id, training_date),
    CONSTRAINT chk_training_status CHECK (completion_status IN ('Completed', 'Absent'))
);